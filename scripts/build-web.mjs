// Bundles src/web/core.ts into mednest/core.js (ESM) for the static web app.
// Run: npm run build:web   (the output is committed; Vercel serves it as-is.)
import { build } from 'esbuild';

await build({
  entryPoints: ['src/web/core.ts'],
  outfile: 'mednest/core.js',
  bundle: true,
  format: 'esm',
  target: 'es2020',
  platform: 'browser',
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-web.mjs from src/ — do not edit by hand.' },
});
console.log('built mednest/core.js');
