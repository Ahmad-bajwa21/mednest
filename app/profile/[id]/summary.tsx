// S15 — Doctor summary. Built from stored records (not free-written by a model): identity,
// allergies, current medicines, recent results, pattern notes, footer.
import { useCallback } from 'react';
import { ScrollView, View } from 'react-native';
import { useLocalSearchParams, router, useFocusEffect } from 'expo-router';
import { useBundle } from '../../../src/features/useBundle';
import { useTheme } from '../../../src/design/theme';
import { Button, Card, Text } from '../../../src/design/components';
import { BottomTabs } from '../../../src/features/BottomTabs';
import { layout, space } from '../../../src/design/tokens';
import { age } from '../../../src/domain/summary';
import { latestResults } from '../../../src/domain/trends';
import { patternNotes } from '../../../src/domain/patterns';
import { activeMedicines } from '../../../src/domain/types';

export default function DoctorSummary() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const { bundle, reload } = useBundle(id);
  const { c } = useTheme();
  useFocusEffect(useCallback(() => { reload(); }, [reload]));

  if (!bundle) return <View style={{ flex: 1, backgroundColor: c.bg }} />;
  const p = bundle.profile;
  const meds = activeMedicines(bundle);
  const results = latestResults(bundle, 6);
  const notes = patternNotes(bundle);

  const Section = ({ title }: { title: string }) => (
    <Text variant="caption" muted style={{ textTransform: 'uppercase', letterSpacing: 1, marginTop: space.md }}>{title}</Text>
  );

  return (
    <View style={{ flex: 1, backgroundColor: c.bg }}>
      <View style={{ flexDirection: 'row', alignItems: 'center', padding: layout.screenPadding, paddingTop: space.xl }}>
        <Button kind="text" title="‹" onPress={() => router.replace(`/profile/${id}`)} />
        <Text variant="title" style={{ flex: 1 }}>Doctor summary</Text>
      </View>
      <ScrollView contentContainerStyle={{ paddingHorizontal: layout.screenPadding, paddingBottom: 80 }}>
        <Card>
          <Text variant="heading">{p.name} · {p.sex ?? '-'}{age(p.birthYear) != null ? ` · ${age(p.birthYear)}` : ''}</Text>
          <Text muted>Allergies: {p.allergies ?? 'none recorded'}</Text>

          <Section title="Current medicines" />
          {meds.length ? meds.map((m) => <Text key={m.id}>{m.name} {m.dose ?? ''} — {m.times.join(', ') || '—'}</Text>) : <Text muted>None</Text>}

          <Section title="Recent results" />
          {results.length ? results.map((r) => <Text key={r.id}>{r.test} {r.value ?? ''}{r.unit ? ' ' + r.unit : ''} ({r.docDate ?? '—'})</Text>) : <Text muted>None</Text>}

          {notes.length ? (
            <>
              <Section title="Notes" />
              {notes.map((n, i) => <Text key={i}>{n.text}</Text>)}
            </>
          ) : null}

          <Text variant="caption" muted style={{ marginTop: space.md }}>
            Generated by MedNest from the patient's own documents. Not a clinical record.
          </Text>
        </Card>
        <Text variant="caption" muted style={{ textAlign: 'center' }}>
          PDF export uses expo-print on-device.
        </Text>
      </ScrollView>
      <BottomTabs id={id!} active="overview" />
    </View>
  );
}
